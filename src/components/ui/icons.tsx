import * as React from "react";

// NeonKit icons. Each glyph is bent glass tube on a 24px grid: one continuous run
// where possible, real bend radii instead of sharp corners, and a blockout gap
// wherever one tube passes behind another. Names and props follow lucide-react.

export type IconProps = Omit<React.SVGProps<SVGSVGElement>, "ref"> & {
  /** Width and height. Default 24. */
  size?: number | string;
  /** Tube thickness in viewBox units. Default 1.75. */
  strokeWidth?: number | string;
  /** Keep the stroke at `strokeWidth` pixels whatever the size. */
  absoluteStrokeWidth?: boolean;
  /** Accessible name. Without it (or an aria-label) the icon is hidden from assistive tech. */
  title?: string;
};

export type Icon = React.ForwardRefExoticComponent<IconProps & React.RefAttributes<SVGSVGElement>>;

/** lucide-react names for the same types, so switching the import path is all a migration needs. */
export type LucideIcon = Icon;
export type LucideProps = IconProps;

/** Path data, one string per tube run, or any SVG children. */
export type IconNode = readonly string[] | React.ReactElement;

const toKebab = (name: string) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([a-zA-Z])(\d)/g, "$1-$2")
    .toLowerCase();

function createIcon(name: string, node: IconNode): Icon {
  const base = `nk-icon nk-icon-${toKebab(name)}`;
  const shape = Array.isArray(node) ? <path d={node.join(" ")} /> : (node as React.ReactElement);

  const Component = React.forwardRef<SVGSVGElement, IconProps>(
    (
      { size = 24, strokeWidth = 1.75, absoluteStrokeWidth, color = "currentColor", title, className, children, ...props },
      ref,
    ) => {
      const px = Number(size);
      const stroke =
        absoluteStrokeWidth && Number.isFinite(px) && px > 0 ? (Number(strokeWidth) * 24) / px : strokeWidth;
      const labelled = Boolean(title || props["aria-label"] || props["aria-labelledby"]);

      return (
        <svg
          ref={ref}
          xmlns="http://www.w3.org/2000/svg"
          width={size}
          height={size}
          viewBox="0 0 24 24"
          fill="none"
          stroke={color}
          strokeWidth={stroke}
          strokeLinecap="round"
          strokeLinejoin="round"
          aria-hidden={labelled ? undefined : true}
          role={labelled ? "img" : undefined}
          className={className ? `${base} ${className}` : base}
          {...props}
        >
          {title ? <title>{title}</title> : null}
          {shape}
          {children}
        </svg>
      );
    },
  );
  Component.displayName = name;
  return Component;
}

