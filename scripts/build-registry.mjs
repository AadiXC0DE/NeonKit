// Builds shadcn-compatible registry items into public/r/ and checks that
// every component only imports what its registry entry declares.

import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const outDir = path.join(root, "public/r");
const siteUrl = (process.env.NEXT_PUBLIC_SITE_URL ?? "https://get-neonkit.vercel.app").replace(/\/$/, "");
const SCHEMA_ITEM = "https://ui.shadcn.com/schema/registry-item.json";

const { items, blocks = [] } = JSON.parse(await readFile(path.join(root, "src/registry/registry.json"), "utf8"));

// src/registry/docs/index.ts is generated from registry.json so the two never drift.
const docIdent = (slug) => `${slug.replace(/-(\w)/g, (_, c) => c.toUpperCase())}Doc`;
const docsIndex = [
  "// Generated by scripts/build-registry.mjs from registry.json. Do not edit.",
  'import type { ComponentDoc } from "../types";',
  ...items.map((item) => `import { doc as ${docIdent(item.slug)} } from "./${item.slug}";`),
  "",
  "export const docs: Record<string, ComponentDoc> = {",
  ...items.map((item) => `  "${item.slug}": ${docIdent(item.slug)},`),
  "};",
  "",
].join("\n");
const docsIndexPath = path.join(root, "src/registry/docs/index.ts");
if ((existsSync(docsIndexPath) ? await readFile(docsIndexPath, "utf8") : "") !== docsIndex) {
  await writeFile(docsIndexPath, docsIndex);
}

// Same for the block lookup used by the /view preview route.
const blockIdent = (slug) => slug.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const blocksIndex = [
  "// Generated by scripts/build-registry.mjs from registry.json. Do not edit.",
  'import type * as React from "react";',
  ...blocks.map((block) => `import ${blockIdent(block.slug)} from "@/components/blocks/${block.slug}";`),
  "",
  "export const blockComponents: Record<string, React.ComponentType> = {",
  ...blocks.map((block) => `  "${block.slug}": ${blockIdent(block.slug)},`),
  "};",
  "",
].join("\n");
const blocksIndexPath = path.join(root, "src/registry/blocks.generated.ts");
if ((existsSync(blocksIndexPath) ? await readFile(blocksIndexPath, "utf8") : "") !== blocksIndex) {
  await writeFile(blocksIndexPath, blocksIndex);
}

const errors = [];
const always = new Set(["react", "react-dom", "@/lib/utils", "@/lib/neon"]);
const slugs = new Set(items.map((item) => item.slug));
const itemDeps = (item) => ["utils", `${siteUrl}/r/neon.json`, ...(item.registryDependencies ?? []).map((slug) => `${siteUrl}/r/${slug}.json`)];

function importsOf(source) {
  const specifiers = new Set();
  for (const match of source.matchAll(/(?:import|export)\s[^"';]*?from\s+["']([^"']+)["']/g)) specifiers.add(match[1]);
  for (const match of source.matchAll(/import\s+["']([^"']+)["']/g)) specifiers.add(match[1]);
  return [...specifiers];
}

const packageName = (specifier) =>
  specifier.startsWith("@") && !specifier.startsWith("@/")
    ? specifier.split("/").slice(0, 2).join("/")
    : specifier.split("/")[0];

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const neonSource = await readFile(path.join(root, "src/lib/neon.ts"), "utf8");
await writeFile(
  path.join(outDir, "neon.json"),
  JSON.stringify(
    {
      $schema: SCHEMA_ITEM,
      name: "neon",
      type: "registry:lib",
      title: "Neon helpers",
      description: "The NeonKit palette and the neonVars() color helper.",
      files: [{ path: "lib/neon.ts", type: "registry:lib", content: neonSource }],
    },
    null,
    2,
  ),
);

for (const item of items) {
  const file = path.join(root, "src/components/ui", `${item.slug}.tsx`);
  if (!existsSync(file)) {
    errors.push(`${item.slug}: missing src/components/ui/${item.slug}.tsx`);
    continue;
  }
  if (!existsSync(path.join(root, "src/registry/docs", `${item.slug}.tsx`))) {
    errors.push(`${item.slug}: missing src/registry/docs/${item.slug}.tsx`);
  }

  const source = await readFile(file, "utf8");
  const declared = new Set(item.dependencies);
  const declaredUi = new Set(item.registryDependencies ?? []);
  const used = new Set();
  const usedUi = new Set();
  for (const slug of declaredUi) {
    if (!slugs.has(slug)) errors.push(`${item.slug}: registryDependencies lists unknown component "${slug}"`);
  }
  for (const specifier of importsOf(source)) {
    if (always.has(specifier)) continue;
    if (specifier.startsWith("@/components/ui/")) {
      const slug = specifier.slice("@/components/ui/".length);
      usedUi.add(slug);
      if (!declaredUi.has(slug)) errors.push(`${item.slug}: imports "${specifier}" but registryDependencies does not list "${slug}"`);
      continue;
    }
    const pkg = packageName(specifier);
    used.add(pkg);
    if (!declared.has(pkg)) errors.push(`${item.slug}: imports "${specifier}" but registry.json does not list "${pkg}"`);
  }
  for (const dep of declared) {
    if (!used.has(dep)) errors.push(`${item.slug}: registry.json lists "${dep}" but the component never imports it`);
  }
  for (const slug of declaredUi) {
    if (!usedUi.has(slug)) errors.push(`${item.slug}: registryDependencies lists "${slug}" but the component never imports it`);
  }

  await writeFile(
    path.join(outDir, `${item.slug}.json`),
    JSON.stringify(
      {
        $schema: SCHEMA_ITEM,
        name: item.slug,
        type: "registry:ui",
        title: item.name,
        description: item.description,
        dependencies: item.dependencies,
        registryDependencies: itemDeps(item),
        files: [{ path: `components/ui/${item.slug}.tsx`, type: "registry:ui", content: source }],
      },
      null,
      2,
    ),
  );
}

for (const block of blocks) {
  const file = path.join(root, "src/components/blocks", `${block.slug}.tsx`);
  if (slugs.has(block.slug)) errors.push(`block ${block.slug}: slug collides with a component`);
  if (!existsSync(file)) {
    errors.push(`block ${block.slug}: missing src/components/blocks/${block.slug}.tsx`);
    continue;
  }
  const source = await readFile(file, "utf8");
  const declared = new Set(block.dependencies);
  const declaredUi = new Set(block.registryDependencies);
  for (const slug of declaredUi) {
    if (!slugs.has(slug)) errors.push(`block ${block.slug}: registryDependencies lists unknown component "${slug}"`);
  }
  const usedUi = new Set();
  for (const specifier of importsOf(source)) {
    if (always.has(specifier)) continue;
    if (specifier.startsWith("@/components/ui/")) {
      const slug = specifier.slice("@/components/ui/".length);
      usedUi.add(slug);
      if (!declaredUi.has(slug)) errors.push(`block ${block.slug}: imports "${specifier}" but registryDependencies does not list "${slug}"`);
      continue;
    }
    const pkg = packageName(specifier);
    if (!declared.has(pkg)) errors.push(`block ${block.slug}: imports "${specifier}" but dependencies does not list "${pkg}"`);
  }
  for (const slug of declaredUi) {
    if (!usedUi.has(slug)) errors.push(`block ${block.slug}: registryDependencies lists "${slug}" but the block never imports it`);
  }
  await writeFile(
    path.join(outDir, `${block.slug}.json`),
    JSON.stringify(
      {
        $schema: SCHEMA_ITEM,
        name: block.slug,
        type: "registry:block",
        title: block.name,
        description: block.description,
        dependencies: block.dependencies,
        registryDependencies: itemDeps(block),
        files: [{ path: `components/${block.slug}.tsx`, type: "registry:component", content: source }],
      },
      null,
      2,
    ),
  );
}

await writeFile(
  path.join(outDir, "registry.json"),
  JSON.stringify(
    {
      $schema: "https://ui.shadcn.com/schema/registry.json",
      name: "neonkit",
      homepage: siteUrl,
      items: [
        { name: "neon", type: "registry:lib", files: [{ path: "lib/neon.ts", type: "registry:lib" }] },
        ...items.map((item) => ({
          name: item.slug,
          type: "registry:ui",
          title: item.name,
          description: item.description,
          dependencies: item.dependencies,
          registryDependencies: itemDeps(item),
          files: [{ path: `components/ui/${item.slug}.tsx`, type: "registry:ui" }],
        })),
        ...blocks.map((block) => ({
          name: block.slug,
          type: "registry:block",
          title: block.name,
          description: block.description,
          dependencies: block.dependencies,
          registryDependencies: itemDeps(block),
          files: [{ path: `components/${block.slug}.tsx`, type: "registry:component" }],
        })),
      ],
    },
    null,
    2,
  ),
);

if (errors.length) {
  console.error(`\nRegistry check failed:\n  ${errors.join("\n  ")}\n`);
  process.exit(1);
}

console.log(`Registry: ${items.length} components, ${blocks.length} blocks + neon helper written to public/r`);
